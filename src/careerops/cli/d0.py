class D0ArgumentParser(argparse.ArgumentParser):
    def error(self, message: str) -> NoReturn:
        if "--json" in sys.argv:
            payload: JsonObject = {
                "scope": "d0_intake",
                "passed": False,
                "errors": ["invalid arguments"],
            }
            print(_stable_json(payload), file=sys.stderr)
            raise SystemExit(2)
        super().error(message)


@dataclass(frozen=True, slots=True)
class CommandResult:
    exit_code: int
    payload: JsonObject


@dataclass(frozen=True, slots=True)
class ScaffoldWrite:
    directory_fd: int
    relative: Path
    content: JsonObject
    signature: FileSignature | None


def main(argv: Sequence[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    handler = cast(Callable[[argparse.Namespace], CommandResult], args.handler)
    result = handler(args)
    _emit(result.payload, json_output=bool(getattr(args, "json", False)))
    return result.exit_code


def _parser() -> argparse.ArgumentParser:
    parser = D0ArgumentParser(
        prog="careerops-d0",
        description="Safe D0 intake evidence status, scaffolding, and validation.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path.cwd(),
        help="repository root containing datasets/ and docs/ (default: current directory)",
    )
    subcommands = parser.add_subparsers(required=True, parser_class=D0ArgumentParser)

    status = subcommands.add_parser("status", help="derive D0 intake status from plan/evidence")
    status.add_argument("--json", action="store_true", help="emit deterministic JSON")
    status.set_defaults(handler=_status)

    scaffold = subcommands.add_parser(
        "scaffold",
        help="create incomplete D0 evidence skeleton files without overwriting by default",
    )
    scaffold.add_argument(
        "--dataset",
        required=True,
        action="append",
        dest="datasets",
        help="dataset ID to scaffold; may be repeated",
    )
    scaffold.add_argument(
        "--force",
        action="store_true",
        help="overwrite only exact, untouched skeletons generated by this CLI",
    )
    scaffold.add_argument("--json", action="store_true", help="emit deterministic JSON")
    scaffold.set_defaults(handler=_scaffold)

    validate = subcommands.add_parser("validate", help="validate D0 evidence")
    validate.add_argument(
        "--contracts-only",
        action="store_true",
        help="validate static contracts only; does not claim pilot evidence completion",
    )
    validate.add_argument("--json", action="store_true", help="emit deterministic JSON")
    validate.set_defaults(handler=_validate)

    return parser


def _status(args: argparse.Namespace) -> CommandResult:
    root = _repo_root(args.root)
    errors: list[str] = []
    plan = _read_json_object(root / PLAN_PATH, errors, "pilot plan")
    datasets = _plan_datasets(plan, errors)

    required_total = 0
    declared_actual_total = 0
    derived_actual_total = 0
    verified_artifact_actual_total = 0
    manifest_references = 0
    manifest_files_present = 0
    scan_reports_present = 0
    scan_reports_zero_unsuppressed = 0
    datasets_satisfied = 0
    dataset_status: list[JsonObject] = []

    for dataset in datasets:
        dataset_id = _safe_dataset_id(dataset.get("id"))
        required = _non_negative_int(dataset.get("pilot_required"))
        declared_actual = _non_negative_int(dataset.get("pilot_actual"))
        required_total += required or 0
        declared_actual_total += declared_actual or 0

        manifest_value = dataset.get("manifest")
        manifest_path: Path | None = None
        manifest_error: str | None = None
        derived_counts = _empty_counts()
        artifact_status: JsonObject = {
            "present": False,
            "digest_verified": False,
        }
        manifest_status: JsonObject = {
            "present": False,
            "identity_verified": False,
        }
        scan_status: JsonObject = {
            "present": False,
            "binding_verified": False,
            "zero_unsuppressed_findings": False,
        }

        if isinstance(manifest_value, str) and manifest_value.strip():
            manifest_references += 1
            manifest_path = _safe_repo_path(root, manifest_value)
            if manifest_path is None:
                manifest_error = "manifest path escapes repository"
            elif manifest_path.is_file():
                manifest_files_present += 1
                manifest_status["present"] = True
                manifest_errors: list[str] = []
                manifest = _read_json_object(
                    manifest_path,
                    manifest_errors,
                    f"{dataset_id} manifest",
                )
                dataset_version = manifest.get("dataset_version")
                if _manifest_identity_verified(
                    expected_dataset_id=dataset_id,
                    manifest_dataset_id=manifest.get("dataset_id"),
                    dataset_version=dataset_version,
                ):
                    manifest_status["identity_verified"] = True
                elif not manifest_errors:
                    manifest_error = _manifest_identity_error(
                        expected_dataset_id=dataset_id,
                        manifest_dataset_id=manifest.get("dataset_id"),
                        dataset_version=dataset_version,
                    )
                artifact = manifest.get("artifact")
                artifact_sha256: Any = None
                actual_artifact_sha256: str | None = None
                if isinstance(artifact, dict):
                    artifact = cast(JsonObject, artifact)
                    artifact_sha256 = artifact.get("sha256")
                    artifact_path = _safe_repo_path(
                        root,
                        artifact.get("path"),
                    )
                    if artifact_path is None:
                        if manifest_error is None:
                            manifest_error = "artifact path missing or unsafe"
                    elif artifact_path.is_file():
                        artifact_status["present"] = True
                        rows, actual_artifact_sha256 = _read_artifact_rows_with_digest(
                            artifact_path,
                            manifest_errors,
                            dataset_id,
                        )
                        derived_counts = _count_rows(rows)
                        if _artifact_digest_verified(
                            artifact_sha256,
                            actual_artifact_sha256,
                        ):
                            artifact_status["digest_verified"] = True
                        elif actual_artifact_sha256 is not None and manifest_error is None:
                            manifest_error = "artifact hash mismatch"
                    else:
                        if manifest_error is None:
                            manifest_error = "artifact file missing"
                scan = manifest.get("pii_scan")
                scan_status = _scan_status(
                    root,
                    scan,
                    manifest_errors,
                    dataset_id=dataset_id,
                    dataset_version=dataset_version,
                    manifest_identity_verified=cast(
                        bool,
                        manifest_status["identity_verified"],
                    ),
                    artifact_sha256=artifact_sha256,
                    actual_artifact_sha256=actual_artifact_sha256,
                )
                if scan_status["present"]:
                    scan_reports_present += 1
                if scan_status["zero_unsuppressed_findings"]:
                    scan_reports_zero_unsuppressed += 1
                if manifest_errors and manifest_error is None:
                    manifest_error = "; ".join(manifest_errors[:3])
            else:
                manifest_error = "manifest file missing"

        real_count = cast(int, derived_counts["real_count"])
        derived_actual_total += real_count
        if artifact_status["digest_verified"] and manifest_status["identity_verified"]:
            verified_artifact_actual_total += real_count
        if (
            required is not None
            and artifact_status["digest_verified"]
            and manifest_status["identity_verified"]
            and real_count >= required
        ):
            datasets_satisfied += 1
        dataset_status.append(
            {
                "id": dataset_id,
                "pilot_required": required,
                "pilot_actual_declared": declared_actual,
                "pilot_actual_derived": real_count,
                "manifest_present": manifest_path is not None and manifest_path.is_file(),
                "manifest": manifest_status,
                "artifact": artifact_status,
                "scan": scan_status,
                "error": manifest_error,
            }
        )

    roles = plan.get("roles")
    quality = plan.get("quality")
    declared_scan_pass = (
        cast(JsonObject, quality).get("pii_scan_passed") if isinstance(quality, dict) else None
    )
    derived_zero_finding_reports = bool(datasets) and scan_reports_zero_unsuppressed == len(
        datasets
    )
    plan_status = _safe_plan_status(plan.get("status"))
    role_status: JsonObject = {
        "data_curator_assigned": _assigned_role(roles, "data_curator"),
        "independent_reviewer_assigned": _assigned_role(roles, "independent_reviewer"),
        "adjudicator_assigned": _assigned_role(roles, "adjudicator"),
        "top_level_role_values_are_distinct": _top_level_role_values_are_distinct(roles),
    }
    quality_status: JsonObject = {
        "pii_scan_passed_declared": (
            declared_scan_pass if isinstance(declared_scan_pass, bool) else None
        ),
        "technical_scan_zero_findings_derived_from_report": derived_zero_finding_reports,
    }
    counts: JsonObject = {
        "dataset_count": len(datasets),
        "manifest_references": manifest_references,
        "manifest_files_present": manifest_files_present,
        "scan_reports_present": scan_reports_present,
        "scan_reports_zero_unsuppressed": scan_reports_zero_unsuppressed,
        "pilot_rows_required": required_total,
        "pilot_rows_declared_actual": declared_actual_total,
        "pilot_rows_derived_actual": derived_actual_total,
        "pilot_rows_derived_from_verified_artifacts": verified_artifact_actual_total,
        "datasets_satisfied_by_derived_rows": datasets_satisfied,
    }
    payload: JsonObject = {
        "scope": "d0_intake",
        "plan": str(PLAN_PATH),
        "plan_status_declared": plan_status,
        "release_qualification_authorized": False,
        "roles": role_status,
        "quality": quality_status,
        "counts": counts,
        "datasets": dataset_status,
        "operator_guidance": _operator_guidance(
            plan_status=plan_status,
            roles=role_status,
            pii_scan_passed=quality_status["pii_scan_passed_declared"],
            datasets=dataset_status,
            pilot_rows_required=required_total,
            pilot_rows_verified=verified_artifact_actual_total,
            errors=errors,
        ),
        "errors": errors,
    }
    return CommandResult(1 if errors else 0, payload)


def _scaffold(args: argparse.Namespace) -> CommandResult:
    root = _repo_root(args.root)
    errors: list[str] = []
    plan = _read_json_object(root / PLAN_PATH, errors, "pilot plan")
    datasets = _plan_datasets(plan, errors)
    known = {
        dataset_id
        for dataset in datasets
        if (dataset_id := _safe_dataset_id_or_none(dataset.get("id"))) is not None
    }
    requested: set[str] = set()
    for index, requested_id in enumerate(cast(list[str], args.datasets or [])):
        if requested_id not in known or not _valid_dataset_id(requested_id):
            errors.append(f"unknown dataset selection at index {index}")
        else:
            requested.add(requested_id)
    datasets = [dataset for dataset in datasets if dataset.get("id") in requested]

    created: list[str] = []
    skipped: list[str] = []
    writes: list[ScaffoldWrite] = []
    directory_fds: list[int] = []
    try:
        if not errors:
            for dataset_index, dataset in enumerate(datasets):
                dataset_id = _safe_dataset_id(dataset.get("id"))
                if not _valid_dataset_id(dataset_id):
                    continue
                directory_fd = _open_scaffold_directory(root, dataset_id)
                if directory_fd is None:
                    errors.append(f"unsafe scaffold path for dataset index {dataset_index}")
                    continue
                directory_fds.append(directory_fd)
                for relative, content in _skeletons_for(dataset).items():
                    exists, signature = _inspect_skeleton_at(
                        directory_fd,
                        relative.name,
                        content,
                    )
                    if exists and not args.force:
                        skipped.append(str(relative))
                        continue
                    if exists and signature is None:
                        errors.append(f"refusing to overwrite non-skeleton file: {relative}")
                        continue
                    writes.append(
                        ScaffoldWrite(
                            directory_fd=directory_fd,
                            relative=relative,
                            content=content,
                            signature=signature,
                        )
                    )

        # Force mode is fail-closed: every target must pass inspection before any replacement.
        if not errors:
            for write in writes:
                write_error = _atomic_write_skeleton(write)
                if write_error is not None:
                    errors.append(f"{write_error}: {write.relative}")
                    break
                created.append(str(write.relative))
    finally:
        for directory_fd in directory_fds:
            with contextlib.suppress(OSError):
                os.close(directory_fd)

    payload: JsonObject = {
        "scope": "d0_intake",
        "created": sorted(created),
        "skipped_existing": sorted(skipped),
        "errors": errors,
        "note": (
            "Scaffolded files are explicitly incomplete and are not referenced by the pilot plan."
        ),
    }
    return CommandResult(1 if errors else 0, payload)


def _validate(args: argparse.Namespace) -> CommandResult:
    root = _repo_root(args.root)
    errors: list[str] = []
    details: JsonObject = {}
    try:
        verifier = _load_verify_m1()
    except (ImportError, OSError, AttributeError, SyntaxError, ValueError) as exc:
        errors.append(f"unable to load verifier: {type(exc).__name__}")
    else:
        try:
            contract_errors, contract_details = verifier.verify_contracts(root)
            errors.extend(str(error) for error in contract_errors)
            details.update(cast(dict[str, Any], contract_details))
            if not args.contracts_only:
                pilot_errors, pilot_details = verifier.verify_full_pilot(root)
                errors.extend(str(error) for error in pilot_errors)
                details.update(cast(dict[str, Any], pilot_details))
        except Exception as exc:  # verifier is script-local; fail closed.
            errors.append(f"verifier failed: {type(exc).__name__}")

    payload: JsonObject = {
        "scope": "d0_intake",
        "mode": "contracts_only" if args.contracts_only else "full",
        "passed": not errors,
        "release_qualification_authorized": False,
        "details": details,
        "errors": errors,
    }
    return CommandResult(0 if not errors else 1, payload)


def _load_verify_m1() -> ModuleType:
    module_path = Path(__file__).resolve()
    package_root = module_path.parents[1]
    source_root = module_path.parents[3]
    candidates = (
        (package_root, package_root / "_trusted" / "verify_m1.py"),
        (source_root, source_root / "scripts" / "verify_m1.py"),
    )
    script: Path | None = None
    for anchor, candidate in candidates:
        try:
            resolved_anchor = anchor.resolve(strict=True)
            resolved_candidate = candidate.resolve(strict=True)
            resolved_candidate.relative_to(resolved_anchor)
        except (FileNotFoundError, OSError, ValueError):
            continue
        if resolved_candidate.is_file():
            script = resolved_candidate
            break
    if script is None:
        raise FileNotFoundError("trusted verify_m1.py is unavailable")
    spec = importlib.util.spec_from_file_location("careerops_d0_verify_m1", script)
    if spec is None or spec.loader is None:
        raise ImportError("scripts/verify_m1.py cannot be imported")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name in ("verify_contracts", "verify_full_pilot"):
        if not callable(getattr(module, name, None)):
            raise AttributeError(f"missing verifier function: {name}")
    return module


