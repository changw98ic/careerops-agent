def _repo_root(value: Path) -> Path:
    return value.expanduser().resolve()


def _read_json_object(path: Path, errors: list[str], label: str) -> JsonObject:
    parsed, _ = _read_json_object_with_digest(path, errors, label)
    return parsed


def _read_json_object_with_digest(
    path: Path,
    errors: list[str],
    label: str,
) -> tuple[JsonObject, str | None]:
    payload = _read_bounded_bytes(path, MAX_JSON_BYTES, errors, label)
    if payload is None:
        return {}, None
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError:
        errors.append(f"{label} must be UTF-8")
        return {}, None
    try:
        parsed = json.loads(
            text,
            parse_constant=_reject_non_finite_json,
            object_pairs_hook=_reject_duplicate_json_keys,
        )
    except (json.JSONDecodeError, ValueError, RecursionError) as exc:
        errors.append(f"{label} is invalid JSON: {exc}")
        return {}, None
    if not isinstance(parsed, dict):
        errors.append(f"{label} must be a JSON object")
        return {}, None
    return cast(JsonObject, parsed), hashlib.sha256(payload).hexdigest()


def _read_artifact_rows_with_digest(
    path: Path,
    errors: list[str],
    dataset_id: str,
) -> tuple[list[JsonObject], str | None]:
    payload = _read_bounded_bytes(path, MAX_ARTIFACT_BYTES, errors, f"{dataset_id}: artifact")
    if payload is None:
        return [], None
    digest = hashlib.sha256(payload).hexdigest()
    try:
        text = payload.decode("utf-8")
    except UnicodeDecodeError:
        errors.append(f"{dataset_id}: artifact must be UTF-8")
        return [], None
    stripped = text.strip()
    if not stripped:
        return [], digest
    raw_rows: list[Any] = []
    try:
        parsed = json.loads(
            stripped,
            parse_constant=_reject_non_finite_json,
            object_pairs_hook=_reject_duplicate_json_keys,
        )
    except (json.JSONDecodeError, ValueError, RecursionError):
        for line_number, line in enumerate(text.splitlines(), start=1):
            if not line.strip():
                continue
            if len(raw_rows) >= MAX_ARTIFACT_ROWS:
                errors.append(f"{dataset_id}: artifact exceeds row limit")
                return [], None
            try:
                raw_rows.append(
                    json.loads(
                        line,
                        parse_constant=_reject_non_finite_json,
                        object_pairs_hook=_reject_duplicate_json_keys,
                    )
                )
            except (json.JSONDecodeError, ValueError, RecursionError) as exc:
                errors.append(f"{dataset_id}: invalid JSONL artifact line {line_number}: {exc}")
                return [], None
    else:
        raw_rows = cast(list[Any], parsed) if isinstance(parsed, list) else [parsed]
    if len(raw_rows) > MAX_ARTIFACT_ROWS:
        errors.append(f"{dataset_id}: artifact exceeds row limit")
        return [], None
    rows: list[JsonObject] = []
    for index, row in enumerate(raw_rows):
        if isinstance(row, dict):
            rows.append(cast(JsonObject, row))
        else:
            errors.append(f"{dataset_id}: artifact row {index + 1} must be an object")
    if len(rows) != len(raw_rows):
        return rows, None
    return rows, digest


def _plan_datasets(plan: JsonObject, errors: list[str]) -> list[JsonObject]:
    raw = plan.get("datasets")
    if not isinstance(raw, list):
        errors.append("pilot plan datasets must be an array")
        return []
    datasets: list[JsonObject] = []
    for index, item in enumerate(cast(list[Any], raw)):
        if isinstance(item, dict):
            dataset = cast(JsonObject, item)
            if _safe_dataset_id_or_none(dataset.get("id")) is None:
                errors.append(f"pilot plan dataset {index} has invalid id")
            datasets.append(dataset)
        else:
            errors.append(f"pilot plan dataset {index} must be an object")
    return datasets


def _scan_status(
    root: Path,
    scan: Any,
    errors: list[str],
    *,
    dataset_id: str,
    dataset_version: Any,
    manifest_identity_verified: bool,
    artifact_sha256: Any,
    actual_artifact_sha256: Any,
) -> JsonObject:
    status: JsonObject = {
        "present": False,
        "binding_verified": False,
        "zero_unsuppressed_findings": False,
    }
    if not isinstance(scan, dict):
        return status
    scan = cast(JsonObject, scan)
    expected_scan_sha256 = scan.get("sha256")
    path = _safe_repo_path(root, scan.get("path"))
    if path is None or not path.is_file():
        return status
    status["present"] = True
    report, actual_scan_sha256 = _read_json_object_with_digest(path, errors, "scan report")
    if (
        not manifest_identity_verified
        or not _is_sha256(expected_scan_sha256)
        or actual_scan_sha256 != expected_scan_sha256
        or not _is_sha256(artifact_sha256)
        or not _is_sha256(actual_artifact_sha256)
        or actual_artifact_sha256 != artifact_sha256
        or not isinstance(dataset_version, str)
        or not dataset_version.strip()
    ):
        return status

    expected_report_values = {
        "version": REPORT_VERSION,
        "scan_scope": SCAN_SCOPE,
        "dataset_id": dataset_id,
        "dataset_version": dataset_version,
        "artifact_sha256": artifact_sha256,
        "tool": TOOL_NAME,
        "tool_version": TOOL_VERSION,
        "rule_set_version": RULE_SET_VERSION,
        "rule_set_sha256": RULE_SET_SHA256,
    }
    if any(report.get(key) != value for key, value in expected_report_values.items()):
        return status

    status["binding_verified"] = True
    findings = report.get("unsuppressed_findings")
    count = report.get("unsuppressed_findings_count")
    findings_count = len(cast(list[object], findings)) if isinstance(findings, list) else None
    status["zero_unsuppressed_findings"] = (
        isinstance(findings, list)
        and isinstance(count, int)
        and not isinstance(count, bool)
        and count == findings_count
        and count == 0
    )
    return status


def _is_sha256(value: Any) -> bool:
    return isinstance(value, str) and SHA256_RE.fullmatch(value) is not None


def _artifact_digest_verified(expected: Any, actual: Any) -> bool:
    return _is_sha256(expected) and isinstance(actual, str) and actual == expected


def _manifest_identity_verified(
    *,
    expected_dataset_id: str,
    manifest_dataset_id: Any,
    dataset_version: Any,
) -> bool:
    return (
        manifest_dataset_id == expected_dataset_id
        and isinstance(dataset_version, str)
        and bool(dataset_version.strip())
    )


def _manifest_identity_error(
    *,
    expected_dataset_id: str,
    manifest_dataset_id: Any,
    dataset_version: Any,
) -> str:
    if manifest_dataset_id != expected_dataset_id:
        return "manifest dataset ID does not match pilot plan"
    if not isinstance(dataset_version, str) or not dataset_version.strip():
        return "manifest dataset version missing"
    return "manifest identity is invalid"


def _count_rows(rows: list[JsonObject]) -> JsonObject:
    counts = _empty_counts()
    groups: dict[str, set[str]] = {split: set() for split in SPLITS}
    for row in rows:
        split = row.get("split")
        if split in SPLITS:
            cast(dict[str, int], counts["split_counts"])[cast(str, split)] += 1
            group_id = row.get("group_id")
            if isinstance(group_id, str):
                groups[cast(str, split)].add(group_id)
        if row.get("synthetic") is True:
            counts["synthetic_count"] = cast(int, counts["synthetic_count"]) + 1
        elif row.get("synthetic") is False:
            counts["real_count"] = cast(int, counts["real_count"]) + 1
    counts["row_count"] = len(rows)
    counts["group_count"] = len(
        {group for split_groups in groups.values() for group in split_groups}
    )
    counts["group_split_counts"] = {split: len(groups[split]) for split in SPLITS}
    return counts


def _empty_counts() -> JsonObject:
    return {
        "row_count": 0,
        "real_count": 0,
        "synthetic_count": 0,
        "split_counts": {split: 0 for split in SPLITS},
        "group_count": 0,
        "group_split_counts": {split: 0 for split in SPLITS},
    }


def _assigned_role(roles: Any, key: str) -> bool:
    if not isinstance(roles, dict):
        return False
    value = cast(dict[str, Any], roles).get(key)
    return isinstance(value, str) and bool(value.strip())


def _top_level_role_values_are_distinct(roles: Any) -> bool:
    if not isinstance(roles, dict):
        return False
    role_values: list[str] = []
    for key in ("data_curator", "independent_reviewer", "adjudicator"):
        value = cast(dict[str, Any], roles).get(key)
        if not isinstance(value, str) or not value.strip():
            return False
        role_values.append(value)
    return len(set(role_values)) == len(role_values)


def _operator_guidance(
    *,
    plan_status: str,
    roles: JsonObject,
    pii_scan_passed: Any,
    datasets: list[JsonObject],
    pilot_rows_required: int,
    pilot_rows_verified: int,
    errors: list[str],
) -> JsonObject:
    """Return bounded, non-authoritative operator next steps from status telemetry."""

    blockers: set[str] = set()
    actions: set[str] = {"run_full_validate_json"}
    if plan_status != "completed":
        blockers.add("plan_not_completed")
        actions.add("complete_frozen_pilot_plan")

    missing_roles = False
    for role, blocker in (
        ("data_curator_assigned", "data_curator_unassigned"),
        ("independent_reviewer_assigned", "independent_reviewer_unassigned"),
        ("adjudicator_assigned", "adjudicator_unassigned"),
    ):
        if roles.get(role) is not True:
            blockers.add(blocker)
            missing_roles = True
    if not missing_roles and roles.get("top_level_role_values_are_distinct") is not True:
        blockers.add("pilot_roles_not_distinct")
    if missing_roles or "pilot_roles_not_distinct" in blockers:
        actions.add("assign_distinct_pilot_roles")

    if pii_scan_passed is not True:
        blockers.add("pii_scan_not_declared_passed")

    manifest_present = _count_dataset_status_flags(datasets, "manifest", "present")
    manifest_identity_verified = _count_dataset_status_flags(
        datasets,
        "manifest",
        "identity_verified",
    )
    artifact_digest_verified = _count_dataset_status_flags(
        datasets,
        "artifact",
        "digest_verified",
    )
    scan_present = _count_dataset_status_flags(datasets, "scan", "present")
    scan_binding_verified = _count_dataset_status_flags(datasets, "scan", "binding_verified")
    scan_zero_findings = _count_dataset_status_flags(
        datasets,
        "scan",
        "zero_unsuppressed_findings",
    )
    if manifest_present < len(datasets):
        blockers.add("manifest_missing")
    if manifest_identity_verified < manifest_present:
        blockers.add("manifest_identity_unverified")
    if artifact_digest_verified < manifest_identity_verified:
        blockers.add("artifact_digest_unverified")
    if pilot_rows_verified < pilot_rows_required:
        blockers.add("pilot_rows_shortfall")
        actions.add("intake_real_pilot_rows")
    if manifest_present < len(datasets) or manifest_identity_verified < manifest_present:
        actions.add("attach_verified_evidence_manifests")
    if artifact_digest_verified < manifest_identity_verified:
        actions.add("attach_verified_evidence_manifests")

    if scan_present < len(datasets):
        blockers.add("scan_report_missing")
    if scan_binding_verified < scan_present:
        blockers.add("scan_binding_unverified")
    if scan_zero_findings < scan_binding_verified:
        blockers.add("scan_zero_findings_unverified")
    if (
        pii_scan_passed is not True
        or scan_present < len(datasets)
        or scan_binding_verified < scan_present
        or scan_zero_findings < scan_binding_verified
    ):
        actions.add("record_bound_scan_reports")

    if errors:
        blockers.add("status_input_error")

    return {
        "version": 1,
        "status_is_authoritative_gate": False,
        "authoritative_gate": "d0_validate_full",
        "next_gate": "d0_full_pilot_evidence",
        "blocker_codes": [blocker for blocker in GUIDANCE_BLOCKER_ORDER if blocker in blockers],
        "next_action_codes": [action for action in GUIDANCE_ACTION_ORDER if action in actions],
        "remaining": {
            "pilot_rows": max(pilot_rows_required - pilot_rows_verified, 0),
            "manifests": max(len(datasets) - manifest_present, 0),
            "scan_reports": max(len(datasets) - scan_present, 0),
        },
    }


def _count_dataset_status_flags(
    datasets: list[JsonObject],
    section: str,
    field: str,
) -> int:
    return sum(
        1
        for dataset in datasets
        if isinstance(dataset.get(section), dict)
        and cast(JsonObject, dataset[section]).get(field) is True
    )


def _safe_repo_path(root: Path, value: Any) -> Path | None:
    if not isinstance(value, str) or not value.strip():
        return None
    candidate = Path(value)
    if candidate.is_absolute():
        return None
    try:
        resolved = (root / candidate).resolve()
        resolved.relative_to(root)
    except (OSError, ValueError):
        return None
    return resolved


def _open_scaffold_directory(root: Path, dataset_id: str) -> int | None:
    if not _valid_dataset_id(dataset_id):
        return None
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    descriptors: list[int] = []
    try:
        root_fd = os.open(root, flags)
        descriptors.append(root_fd)
        datasets_fd = _open_directory_at(root_fd, "datasets", flags=flags, create=False)
        if datasets_fd is None:
            return None
        descriptors.append(datasets_fd)
        intake_fd = _open_directory_at(datasets_fd, "d0-intake", flags=flags, create=True)
        if intake_fd is None:
            return None
        descriptors.append(intake_fd)
        dataset_fd = _open_directory_at(intake_fd, dataset_id, flags=flags, create=True)
        if dataset_fd is None:
            return None
        return dataset_fd
    except OSError:
        return None
    finally:
        for descriptor in reversed(descriptors):
            with contextlib.suppress(OSError):
                os.close(descriptor)


def _open_directory_at(
    parent_fd: int,
    name: str,
    *,
    flags: int,
    create: bool,
) -> int | None:
    try:
        return os.open(name, flags, dir_fd=parent_fd)
    except FileNotFoundError:
        if not create:
            return None
    except OSError:
        return None
    try:
        os.mkdir(name, mode=0o700, dir_fd=parent_fd)
    except FileExistsError:
        pass
    except OSError:
        return None
    try:
        return os.open(name, flags, dir_fd=parent_fd)
    except OSError:
        return None


def _inspect_skeleton_at(
    directory_fd: int,
    name: str,
    expected: JsonObject,
) -> tuple[bool, FileSignature | None]:
    if Path(name).name != name:
        return True, None
    flags = os.O_RDONLY | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
    try:
        descriptor = os.open(name, flags, dir_fd=directory_fd)
    except FileNotFoundError:
        return False, None
    except OSError:
        return True, None
    try:
        before = os.fstat(descriptor)
        if not stat.S_ISREG(before.st_mode):
            return True, None
        payload = bytearray()
        while len(payload) <= MAX_JSON_BYTES:
            chunk = os.read(descriptor, min(1024 * 1024, MAX_JSON_BYTES + 1 - len(payload)))
            if not chunk:
                break
            payload.extend(chunk)
        after = os.fstat(descriptor)
    except OSError:
        return True, None
    finally:
        with contextlib.suppress(OSError):
            os.close(descriptor)
    before_signature = _file_signature(before)
    if before_signature != _file_signature(after):
        return True, None
    if bytes(payload) != _skeleton_bytes(expected):
        return True, None
    return True, before_signature


def _file_signature(value: os.stat_result) -> FileSignature:
    return (value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns, value.st_ctime_ns)


def _skeleton_bytes(content: JsonObject) -> bytes:
    return (_stable_json(content) + "\n").encode("utf-8")


def _atomic_write_skeleton(write: ScaffoldWrite) -> str | None:
    temporary_name: str | None = None
    descriptor = -1
    try:
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | getattr(os, "O_CLOEXEC", 0)
        for _attempt in range(8):
            candidate = f".{write.relative.name}.{secrets.token_hex(8)}.tmp"
            try:
                descriptor = os.open(
                    candidate,
                    flags,
                    0o600,
                    dir_fd=write.directory_fd,
                )
            except FileExistsError:
                continue
            temporary_name = candidate
            break
        if temporary_name is None:
            return "unable to allocate scaffold temporary file"
        with os.fdopen(descriptor, "wb") as file:
            descriptor = -1
            file.write(_skeleton_bytes(write.content))
            file.flush()
            os.fsync(file.fileno())
        if write.signature is None:
            os.link(
                temporary_name,
                write.relative.name,
                src_dir_fd=write.directory_fd,
                dst_dir_fd=write.directory_fd,
                follow_symlinks=False,
            )
        else:
            exists, current_signature = _inspect_skeleton_at(
                write.directory_fd,
                write.relative.name,
                write.content,
            )
            if not exists or current_signature != write.signature:
                return "scaffold target changed after preflight"
            os.replace(
                temporary_name,
                write.relative.name,
                src_dir_fd=write.directory_fd,
                dst_dir_fd=write.directory_fd,
            )
            temporary_name = None
        with contextlib.suppress(OSError):
            os.fsync(write.directory_fd)
    except FileExistsError:
        return "scaffold target changed after preflight"
    except OSError:
        return "unable to write scaffold file"
    finally:
        if descriptor >= 0:
            with contextlib.suppress(OSError):
                os.close(descriptor)
        if temporary_name is not None:
            with contextlib.suppress(OSError):
                os.unlink(temporary_name, dir_fd=write.directory_fd)
    return None


def _read_bounded_bytes(
    path: Path,
    maximum_bytes: int,
    errors: list[str],
    label: str,
) -> bytes | None:
    try:
        with path.open("rb") as file:
            payload = file.read(maximum_bytes + 1)
    except FileNotFoundError:
        errors.append(f"{label} is missing")
        return None
    except OSError:
        errors.append(f"{label} is unreadable")
        return None
    if len(payload) > maximum_bytes:
        errors.append(f"{label} exceeds size limit")
        return None
    return payload


def _valid_dataset_id(value: str) -> bool:
    return value in FROZEN_DATASET_IDS and DATASET_ID_RE.fullmatch(value) is not None


def _stable_json(value: JsonObject) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)


def _emit(payload: JsonObject, *, json_output: bool) -> None:
    if json_output:
        print(_stable_json(payload))
        return
    passed = payload.get("passed")
    if isinstance(passed, bool):
        print("PASS" if passed else "FAIL")
    else:
        print(payload.get("scope", "careerops-d0"))
    counts = payload.get("counts")
    if isinstance(counts, dict):
        for key, value in sorted(cast(dict[str, object], counts).items()):
            print(f"{key}: {value}")
    for item in cast(list[str], payload.get("created", [])):
        print(f"created: {item}")
    for item in cast(list[str], payload.get("skipped_existing", [])):
        print(f"skipped: {item}")
    errors = payload.get("errors")
    if isinstance(errors, list):
        for error in cast(list[object], errors):
            print(f"error: {error}", file=sys.stderr)


def _safe_dataset_id(value: Any) -> str:
    return value if isinstance(value, str) and value in FROZEN_DATASET_IDS else "<invalid>"


def _safe_dataset_id_or_none(value: Any) -> str | None:
    return value if isinstance(value, str) and value in FROZEN_DATASET_IDS else None


def _safe_plan_status(value: Any) -> str:
    return value if isinstance(value, str) and value in KNOWN_PLAN_STATUSES else "<invalid>"


def _non_negative_int(value: Any) -> int | None:
    if isinstance(value, int) and not isinstance(value, bool) and value >= 0:
        return value
    return None


def _reject_non_finite_json(value: str) -> None:
    raise ValueError(f"non-finite JSON number is forbidden: {value}")


def _reject_duplicate_json_keys(pairs: list[tuple[str, Any]]) -> JsonObject:
    result: JsonObject = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON object key is forbidden")
        result[key] = value
    return result


